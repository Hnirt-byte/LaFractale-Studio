MANIFEST_SCHEMA = "lafractale-engine-manifest-v1"
#: Minimum distance between any drawn object / text and the page edge (0.5 in).
PRINT_SAFE_MARGIN_PT = 36.0
TOL = 0.06
#: Farthest a number label may sit from its dot (renderer offsets stay below 40 pt).
LABEL_REACH = 45.0
HELVETICA_WARNING = ("Référence Helvetica (base-14) non intégrée dans le rendu historique : "
                     "écart connu du moteur existant, hors périmètre B3-B.1")


class _Checks:
    """Aggregate evaluations per check id, in a stable order."""

    def __init__(self) -> None:
        self._evaluations: dict[str, int] = {}
        self._failures: dict[str, list[str]] = {}
        self._warnings: dict[str, str] = {}

    def expect(self, check_id: str, condition: bool, failure: str) -> None:
        self._evaluations[check_id] = self._evaluations.get(check_id, 0) + 1
        failures = self._failures.setdefault(check_id, [])
        if not condition:
            failures.append(failure)

    def expect_all(self, check_id: str, failures: Iterable[str]) -> None:
        failures = list(failures)
        self._evaluations[check_id] = self._evaluations.get(check_id, 0) + 1
        self._failures.setdefault(check_id, []).extend(failures)

    def warn(self, check_id: str, message: str) -> None:
        self._warnings[check_id] = message

    def as_list(self) -> list[dict[str, str]]:
        result = []
        for check_id, count in self._evaluations.items():
            failures = self._failures[check_id]
            if failures:
                result.append({"id": check_id, "status": "FAIL", "detail": "; ".join(failures[:8])})
            else:
                result.append({"id": check_id, "status": "PASS", "detail": f"{count} contrôle(s)"})
        for check_id, message in self._warnings.items():
            result.append({"id": check_id, "status": "WARN", "detail": message})
        return result


def _numbers(obj: Any) -> list[float]:
    if isinstance(obj, bool):
        return []
    if isinstance(obj, (int, float)):
        return [round(float(obj), 2)]
    if hasattr(obj, "x") and hasattr(obj, "y") and not hasattr(obj, "x0"):
        return [round(obj.x, 2), round(obj.y, 2)]
    if hasattr(obj, "x0") and hasattr(obj, "y1"):
        return [round(obj.x0, 2), round(obj.y0, 2), round(obj.x1, 2), round(obj.y1, 2)]
    if hasattr(obj, "ul") and hasattr(obj, "lr"):
        return [v for point in (obj.ul, obj.ur, obj.ll, obj.lr) for v in _numbers(point)]
    return []


def _color(value: Any) -> tuple[float, ...] | None:
    return None if value is None else tuple(round(float(v), 2) for v in value)


def _drawing_key(drawing: dict) -> tuple:
    items = tuple((item[0], tuple(v for part in item[1:] for v in _numbers(part))) for item in drawing["items"])
    return (items, round(drawing.get("width") or 0.0, 2), _color(drawing.get("color")),
            _color(drawing.get("fill")))


def _drawing_multiset(page: Any) -> Counter:
    return Counter(_drawing_key(d) for d in page.get_drawings())


def _line_vertices(drawing: dict) -> list[tuple[float, float]] | None:
    """Vertices of a polyline made only of straight segments, else None."""
    items = drawing["items"]
    if not items or any(item[0] != "l" for item in items):
        return None
    vertices = [(items[0][1].x, items[0][1].y)]
    for item in items:
        start, end = (item[1].x, item[1].y), (item[2].x, item[2].y)
        if abs(start[0] - vertices[-1][0]) > TOL or abs(start[1] - vertices[-1][1]) > TOL:
            return None
        vertices.append(end)
    return vertices


def _extra_drawings(answer_page: Any, interior_page: Any) -> list[dict]:
    """Drawings present on the corrigé page and absent from the fiche page."""
    remaining = _drawing_multiset(interior_page)
    extra = []
    for drawing in answer_page.get_drawings():
        key = _drawing_key(drawing)
        if remaining[key] > 0:
            remaining[key] -= 1
        else:
            extra.append(drawing)
    return extra


def _sign(value: float) -> int:
    return 0 if abs(value) < TOL else (1 if value > 0 else -1)


def _maze_coherence(activity: Activity, interior: Any, answer: Any) -> list[str]:
    errors = []
    size = activity.geometry["size"]
    extra = _extra_drawings(answer, interior)
    if len(extra) != 1:
        return [f"labyrinthe : 1 tracé de solution attendu, {len(extra)} trouvé(s)"]
    vertices = _line_vertices(extra[0])
    path = activity.answer["path"]
    if vertices is None or len(vertices) != len(path):
        return [f"labyrinthe : le tracé du corrigé n'a pas {len(path) - 1} segments droits"]
    lengths = [abs(b[0] - a[0]) + abs(b[1] - a[1]) for a, b in zip(vertices, vertices[1:])]
    if lengths and max(lengths) - min(lengths) > TOL:
        errors.append("labyrinthe : segments de solution de longueurs inégales")
    # PDF y grows upward, PyMuPDF y grows downward: cell dy is the opposite sign.
    drawn = [(_sign(b[0] - a[0]), -_sign(b[1] - a[1])) for a, b in zip(vertices, vertices[1:])]
    expected = [(b[0] - a[0], b[1] - a[1]) for a, b in zip(path, path[1:])]
    if drawn != expected:
        errors.append("labyrinthe : le tracé du corrigé ne suit pas le chemin de l'activité")
    walls = []
    for drawing in interior.get_drawings():
        if abs((drawing.get("width") or 0) - 3.0) < 0.05:
            walls.extend(((i[1].x, i[1].y), (i[2].x, i[2].y)) for i in drawing["items"] if i[0] == "l")
    # Rebuild the walls from the activity's own passages, anchored on the drawn
    # solution (cell size and origin are fitted from it), and compare to the page.
    cell = lengths[0] if lengths else 0.0
    if cell <= 0:
        return errors + ["labyrinthe : taille de cellule indéterminée"]
    ox = vertices[0][0] - (path[0][0] + 0.5) * cell
    top = vertices[0][1] + (path[0][1] + 0.5) * cell  # fitz y of the bottom border
    passages = {frozenset((tuple(a), tuple(b))) for a, b in activity.geometry["open_edges"]}
    expected = []
    for y in range(size):
        for x in range(size):
            if y == 0 or frozenset(((x, y), (x, y - 1))) not in passages:
                expected.append(((ox + x * cell, top - y * cell), (ox + (x + 1) * cell, top - y * cell)))
            if x == 0 or frozenset(((x, y), (x - 1, y))) not in passages:
                expected.append(((ox + x * cell, top - y * cell), (ox + x * cell, top - (y + 1) * cell)))
    expected.append(((ox, top - size * cell), (ox + size * cell, top - size * cell)))
    expected.append(((ox + size * cell, top), (ox + size * cell, top - size * cell)))
    if not _same_segments(expected, walls):
        errors.append("labyrinthe : murs dessinés différents des passages de l'activité")
    for a, b in zip(vertices, vertices[1:]):
        if any(segments_touch(a, b, w0, w1) for w0, w1 in walls):
            errors.append("labyrinthe : le tracé du corrigé traverse un mur dessiné")
            break
    return errors


def _same_segments(expected: list, drawn: list, tol: float = 0.15) -> bool:
    """Multiset equality of undirected segments, within ``tol`` points."""
    if len(expected) != len(drawn):
        return False
    pool = [tuple(sorted(segment)) for segment in drawn]
    for a, b in expected:
        target = tuple(sorted((a, b)))
        for index, candidate in enumerate(pool):
            if all(abs(u - v) <= tol for p, q in zip(target, candidate) for u, v in zip(p, q)):
                del pool[index]
                break
        else:
            return False
    return not pool


def _affine_residual(source: list[float], target: list[float], sign: int) -> float:
    """Worst error of the scale+offset map source -> target with a FIXED orientation.

    ``sign`` is +1 when both axes grow the same way and -1 when the target axis is
    flipped (PyMuPDF y grows downward). An imposed sign makes a mirrored drawing fail.
    """
    span_s, span_t = max(source) - min(source), max(target) - min(target)
    if span_s <= 0 or span_t <= 0:
        return float("inf")
    mean_s, mean_t = sum(source) / len(source), sum(target) / len(target)
    scale = sign * span_t / span_s
    return max(abs(scale * (s - mean_s) + mean_t - t) for s, t in zip(source, target))


def _small_dots(page: Any) -> list[tuple[float, float]]:
    return [((d["rect"].x0 + d["rect"].x1) / 2, (d["rect"].y0 + d["rect"].y1) / 2)
            for d in page.get_drawings()
            if abs(d["rect"].width - 8.2) < 0.4 and abs(d["rect"].height - 8.2) < 0.4]


def _dots_coherence(activity: Activity, interior: Any, answer: Any) -> list[str]:
    errors = []
    count = len(activity.geometry["points"])
    dots = _small_dots(interior)
    if len(dots) != count:
        return [f"points : {len(dots)} points dessinés, {count} attendus"]
    extra = _extra_drawings(answer, interior)
    if len(extra) != 1:
        return [f"points : 1 tracé de solution attendu, {len(extra)} trouvé(s)"]
    vertices = _line_vertices(extra[0])
    if vertices is None or len(vertices) != count + 1:
        return ["points : le tracé du corrigé n'est pas un contour fermé de N segments"]
    if any(abs(v[0] - d[0]) > TOL or abs(v[1] - d[1]) > TOL for v, d in zip(vertices, dots)):
        errors.append("points : le tracé du corrigé ne passe pas par les points dans l'ordre 1..N")
    if abs(vertices[-1][0] - vertices[0][0]) > TOL or abs(vertices[-1][1] - vertices[0][1]) > TOL:
        errors.append("points : le tracé du corrigé ne revient pas au point 1")
    points = activity.geometry["points"]
    if (_affine_residual([p["x"] for p in points], [d[0] for d in dots], +1) > 0.1
            or _affine_residual([p["y"] for p in points], [d[1] for d in dots], -1) > 0.1):
        errors.append("points : positions dessinées différentes des coordonnées de l'activité")
    xs, ys = [d[0] for d in dots], [d[1] for d in dots]
    labels = [w[4] for w in interior.get_text("words")
              if w[4].isdigit() and min(xs) - 50 <= (w[0] + w[2]) / 2 <= max(xs) + 50
              and min(ys) - 50 <= (w[1] + w[3]) / 2 <= max(ys) + 50]
    if Counter(labels) != Counter(str(n) for n in range(1, count + 1)):
        errors.append("points : numéros affichés différents de 1..N")
    numbers = [((w[0] + w[2]) / 2, (w[1] + w[3]) / 2, w[4]) for w in interior.get_text("words") if w[4].isdigit()]
    for n, (dx, dy) in enumerate(dots, start=1):
        if not any(text == str(n) and hypot(wx - dx, wy - dy) <= LABEL_REACH for wx, wy, text in numbers):
            errors.append(f"points : le numéro {n} n'est pas affiché près du point {n}")
    return errors


def _match_coherence(activity: Activity, interior: Any, answer: Any) -> list[str]:
    pairs = activity.answer["left_to_right"]
    extra = _extra_drawings(answer, interior)
    if len(extra) != len(pairs):
        return [f"association : {len(pairs)} liens attendus, {len(extra)} trouvé(s)"]
    links = []
    for drawing in extra:
        vertices = _line_vertices(drawing)
        if vertices is None or len(vertices) != 2:
            return ["association : lien de solution qui n'est pas un segment droit"]
        links.append(vertices)
    left_x, right_x = {round(v[0][0], 1) for v in links}, {round(v[1][0], 1) for v in links}
    if len(left_x) != 1 or len(right_x) != 1 or min(right_x) <= max(left_x):
        return ["association : liens non issus de deux colonnes distinctes"]
    left_rows = sorted({round(v[0][1], 1) for v in links})
    right_rows = sorted({round(v[1][1], 1) for v in links})
    if len(left_rows) != len(pairs) or len(right_rows) != len(pairs):
        return ["association : points d'ancrage non distincts"]
    drawn = sorted((left_rows.index(round(v[0][1], 1)), right_rows.index(round(v[1][1], 1))) for v in links)
    if drawn != sorted(enumerate(pairs)):
        return ["association : liens du corrigé différents des paires de l'activité"]
    return []


_COHERENCE = {"maze": _maze_coherence, "connect_dots": _dots_coherence, "match": _match_coherence}


def _norm(text: str) -> str:
    return " ".join(text.split())


def _pdf_checks(checks: _Checks, spec_set: SpecSet, activities: tuple[Activity, ...],
                interior_path: Path, answer_path: Path) -> None:
    width, height = spec_set.trim[0] * 72, spec_set.trim[1] * 72
    docs = {}
    try:
        for kind, path in (("interior", interior_path), ("answer_key", answer_path)):
            docs[kind] = fitz.open(path)
    except Exception as exc:  # unreadable or malformed PDF
        for doc in docs.values():
            doc.close()
        checks.expect("pdf.readable", False, f"PDF illisible : {exc}")
        return
    try:
        counts_ok = True
        for kind, doc in docs.items():
            checks.expect("pdf.readable", True, "")
            checks.expect(f"pdf.{kind}.page_count", len(doc) == len(activities),
                          f"{kind} : {len(doc)} pages, {len(activities)} attendues")
            if len(doc) != len(activities):
                counts_ok = False
                continue
            for activity, page in zip(activities, doc):
                where = f"{kind} p{activity.page}"
                text = _norm(page.get_text())
                checks.expect("pdf.page_size", abs(page.rect.width - width) < 0.01
                              and abs(page.rect.height - height) < 0.01, f"{where} : format {tuple(page.rect)[2:]}")
                checks.expect("pdf.no_image", not page.get_images(full=True), f"{where} : image inattendue")
                for label, needle in (("scene", activity.scene), ("prompt_fr", activity.prompt_fr),
                                      ("prompt_en", activity.prompt_en), ("label", f"FICHE {activity.page:02d}")):
                    checks.expect(f"pdf.source_text.{label}", _norm(needle) in text,
                                  f"{where} : texte source absent du PDF ({needle!r})")
                checks.expect("pdf.marking.working_draft", "MAQUETTE DE TRAVAIL" in text
                              and "KDP EN ATTENTE" in text, f"{where} : mention de maquette absente")
                is_answer = kind == "answer_key"
                sources = [_norm(activity.scene), _norm(activity.prompt_fr), _norm(activity.prompt_en)]
                # The title appears once; source texts may legitimately contain the same words.
                title_ok = all(text.count(marker) == sum(s.count(marker) for s in sources) + int(present)
                               for marker, present in (("CORRIGÉ", is_answer),
                                                       ("Je joue et j'apprends !", not is_answer)))
                checks.expect("pdf.title", title_ok, f"{where} : titre de fiche/corrigé incohérent")
                margin = PRINT_SAFE_MARGIN_PT
                inside = lambda x0, y0, x1, y1: (x0 >= margin and y0 >= margin  # noqa: E731
                                                 and x1 <= width - margin and y1 <= height - margin)
                checks.expect("pdf.safe_margin.text", all(inside(*w[:4]) for w in page.get_text("words")),
                              f"{where} : texte à moins de {margin} pt du bord")
                checks.expect("pdf.safe_margin.drawings",
                              all(inside(d["rect"].x0, d["rect"].y0, d["rect"].x1, d["rect"].y1)
                                  for d in page.get_drawings()),
                              f"{where} : tracé à moins de {margin} pt du bord")
                fonts = [font[3].lower() for font in page.get_fonts()]
                checks.expect("pdf.fonts.embedded", any("dejavu" in f for f in fonts),
                              f"{where} : police DejaVu intégrée absente")
                if any(f.startswith("helvetica") for f in fonts):
                    checks.warn("pdf.fonts.base14_helvetica_reference", HELVETICA_WARNING)
                try:
                    verify_text_policy(text, forbidden_names=SYNTHETIC_FORBIDDEN_NAMES, location=where)
                except UnsafeEditorialText as exc:
                    checks.expect("pdf.text_policy", False, str(exc))
                else:
                    checks.expect("pdf.text_policy", True, "")
        if not counts_ok:
            return
        # The fiche must never carry the solution; the corrigé must draw exactly
        # the solution of the activity (checked on the drawn geometry itself).
        for activity, p_int, p_ans in zip(activities, docs["interior"], docs["answer_key"]):
            where = f"p{activity.page} ({activity.type})"
            leaked = _drawing_multiset(p_int) - _drawing_multiset(p_ans)
            checks.expect("pdf.answer_superset_of_fiche", not leaked,
                          f"{where} : la fiche contient des tracés absents du corrigé")
            checks.expect_all("pdf.answer_matches_activity",
                              (f"{where} : {m}" for m in _COHERENCE[activity.type](activity, p_int, p_ans)))
    finally:
        for doc in docs.values():
            doc.close()


def content_checks(spec_set: SpecSet, activities: tuple[Activity, ...],
                   interior_path: Path, answer_path: Path) -> list[dict[str, str]]:
    checks = _Checks()
    for activity in activities:
        checks.expect_all("activity.solution_verified",
                          MECHANICS[activity.type].verify(activity))
    try:
        _pdf_checks(checks, spec_set, activities, interior_path, answer_path)
    except Exception as exc:  # malformed PDF content must not hide the other findings
        checks.expect("pdf.analysis", False, f"analyse du PDF impossible : {type(exc).__name__}: {exc}")
    return checks.as_list()


def build_report(spec_set: SpecSet, activities: tuple[Activity, ...],
                 checks: list[dict[str, str]]) -> dict[str, Any]:
    passed = all(check["status"] != "FAIL" for check in checks)
    return {
        "schema": REPORT_SCHEMA,
        "kind": KIND,
        "ready_for_kdp": READY_FOR_KDP,
        "gates": dict(GATES),
        "human_validations_recorded": HUMAN_VALIDATIONS_RECORDED,
        "engine_version": __version__,
        "spec_id": spec_set.spec_id,
        "source_sha256": spec_set.source_sha256,
        "seed": spec_set.seed,
        "page_count": len(activities),
        "pages": [{"page": a.page, "unit_id": a.id, "mechanic": a.type,
                   "activity_fingerprint": content_fingerprint(a)} for a in activities],
        "checks": checks,
        "pass": passed,
    }


def build_manifest(spec_set: SpecSet, file_hashes: dict[str, str]) -> dict[str, Any]:
    """Relative POSIX paths only; hashes of every other file of the package."""
    return {
        "schema": MANIFEST_SCHEMA,
        "kind": KIND,
        "ready_for_kdp": READY_FOR_KDP,
        "gates": dict(GATES),
        "engine_version": __version__,
        "spec_id": spec_set.spec_id,
        "seed": spec_set.seed,
        "page_count": len(spec_set.pages),
        "files": dict(sorted(file_hashes.items())),
    }


def _inventory_errors(root: Path) -> list[str]:
    errors = []
    expected_dirs = {SOURCE_DIR}
    seen: set[str] = set()
    for entry in sorted(root.iterdir(), key=lambda p: p.name):
        mode = entry.lstat().st_mode
        if entry.name in expected_dirs:
            if not stat.S_ISDIR(mode):
                errors.append(f"inventaire : {entry.name} n'est pas un répertoire réel")
                continue
            for child in sorted(entry.iterdir(), key=lambda p: p.name):
                relative = f"{entry.name}/{child.name}"
                seen.add(relative)
                if not stat.S_ISREG(child.lstat().st_mode):
                    errors.append(f"inventaire : entrée non régulière {relative}")
        else:
            seen.add(entry.name)
            if not stat.S_ISREG(mode):
                errors.append(f"inventaire : entrée non régulière {entry.name}")
    for name in sorted(seen - set(PACKAGE_FILES)):
        errors.append(f"inventaire : fichier non autorisé {name}")
    for name in sorted(set(PACKAGE_FILES) - seen):
        errors.append(f"inventaire : fichier manquant {name}")
    return errors


def audit_package(out_dir: Path, spec_set: SpecSet, activities: tuple[Activity, ...]) -> list[str]:
    """Full audit of a package against a source. Empty list = every check passed."""
    try:
        with audit_root_dirfd(out_dir) as anchored:
            return _audit_anchored(anchored, spec_set, activities)
    except (UnsafeOutputPath, OSError) as exc:
        return [f"répertoire d'audit non sûr : {exc}"]


def _audit_anchored(root: Path, spec_set: SpecSet, activities: tuple[Activity, ...]) -> list[str]:
    errors = _inventory_errors(root)
    if errors:
        return errors
    data = {name: (root / name).read_bytes() for name in PACKAGE_FILES}
    # Manifest: exact content, relative paths, hashes of every other file.
    expected_manifest = canonical_json_bytes(build_manifest(spec_set, {
        name: sha256_hex(content) for name, content in data.items() if name != MANIFEST_NAME}))
    if data[MANIFEST_NAME] != expected_manifest:
        errors.append("manifest.json : contenu ou empreintes différents de la source régénérée")
    if sha256_hex(data[SOURCE_NAME]) != spec_set.source_sha256:
        errors.append("sources/spec.json : différent de la source auditée")
    if data[ACTIVITIES_NAME] != canonical_json_bytes([a.as_dict() for a in activities]):
        errors.append("activities.json : différent des activités régénérées depuis la source")
    # Independent replay: byte-for-byte identical PDFs from the same source.
    with tempfile.TemporaryDirectory(prefix="lafractale-engine-qa-") as scratch:
        try:
            interior, answer = render_slice(spec_set, activities, Path(scratch))
        except EngineError as exc:
            return errors + [f"rejeu du rendu impossible : {exc}"]
        for name, replay in ((INTERIOR_NAME, interior), (ANSWER_NAME, answer)):
            if data[name] != replay.read_bytes():
                errors.append(f"{name} : différent du rendu régénéré depuis la source")
        checks = content_checks(spec_set, activities, root / INTERIOR_NAME, root / ANSWER_NAME)
    errors.extend(f"{c['id']} : {c['detail']}" for c in checks if c["status"] == "FAIL")
    if data[REPORT_NAME] != canonical_json_bytes(build_report(spec_set, activities, checks)):
        errors.append("quality_report.json : différent du rapport recalculé")
    return errors
