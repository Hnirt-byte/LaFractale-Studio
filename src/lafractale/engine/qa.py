"""Automated QA of a slice package: both PDFs, the solution drawn in the corrigé,
the source texts actually present in the PDF, and the package integrity.

Ground truth is always recomputed from the source (``activities`` regenerated by
the pipeline); no file of the audited package is an authority about itself.
Everything here is deterministic: no timestamps, no absolute paths.
"""
